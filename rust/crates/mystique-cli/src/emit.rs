//! `--emit-constants`: turn a report into the generated table in
//! `mystique-protocol/src/commands.rs`.
//!
//! Mechanical by design. Only command bytes that were **echoed back** are emitted —
//! a neutral `55 2E 00` ACK proves receipt, not recognition. The pipe comes from the
//! entry and the semantic grade from the hand-maintained command table; an echo never
//! upgrades a command to `Verified`. No meaning is inferred. The report path is
//! recorded so the constant can be traced back to the run that produced it.

use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use mystique_protocol::commands::{find, Command, Evidence};

use crate::report::Entry;

pub const BEGIN: &str = "// BEGIN GENERATED: observed-commands";
pub const END: &str = "// END GENERATED: observed-commands";

/// Renders the contents of the generated block, markers excluded.
pub fn render(entries: &[Entry], source: &str) -> String {
    let source = source.replace('\\', "/").replace('"', "\\\"");
    let source_quoted = format!("\"{source}\"");

    // One entry per echoed command, preferring a successful reply.
    let mut chosen: Vec<&Entry> = Vec::new();
    let mut seen: Vec<u8> = Vec::new();
    let mut sorted: Vec<&Entry> = entries.iter().collect();
    sorted.sort_by_key(|entry| (entry.cmd, !entry.succeeded()));

    for entry in sorted {
        let echoed = entry.cmd != 0x00 && entry.echo == Some(entry.cmd);
        if !echoed || seen.contains(&entry.cmd) {
            continue;
        }
        seen.push(entry.cmd);
        chosen.push(entry);
    }
    chosen.sort_by_key(|entry| entry.cmd);

    let mut block = String::new();
    block.push_str("//\n");
    block.push_str(&format!(
        "// Generated by `mystique explore --emit-constants`. Do not edit by hand.\n// Source: {source}\n"
    ));
    block.push_str("pub const OBSERVED_COMMANDS: &[ObservedCommand] = &[\n");

    for entry in chosen {
        let pipe = match entry.pipe.as_str() {
            "init" => "Pipe::Init",
            _ => "Pipe::Data",
        };
        let echo = match entry.echo {
            Some(echo) => format!("Some(0x{echo:02X})"),
            None => "None".to_owned(),
        };
        let result = match entry.result_code {
            Some(result) => format!("Some(0x{result:02X})"),
            None => "None".to_owned(),
        };
        let reply_len = match entry.reply_len {
            Some(len) => format!("Some({len})"),
            None => "None".to_owned(),
        };
        let payload_gated = Command::from_code(entry.cmd)
            .map(Command::requires_payload)
            .unwrap_or(false);
        let grade = find(entry.cmd)
            .map(|info| info.semantics)
            .unwrap_or(Evidence::Unknown);
        block.push_str(&format!(
            "    // 0x{:02X} - {} on {}, echo {}, result {}, {} bytes, {} ms.\n",
            entry.cmd,
            if payload_gated {
                "recognised with a payload"
            } else {
                "replied"
            },
            entry.pipe,
            echo,
            result,
            reply_len,
            entry.elapsed_ms,
        ));
        block.push_str(&format!(
            "    // Grade: {} (semantics). Report: {source}\n",
            grade.label()
        ));
        block.push_str(&format!(
            "    ObservedCommand {{ code: 0x{:02X}, pipes: &[{pipe}], payload_gated: {payload_gated}, grade: Evidence::{}, sources: &[{source_quoted}] }},\n",
            entry.cmd,
            grade.label()
        ));
    }

    block.push_str("];\n");
    block
}

/// Replaces the content between the markers, leaving everything else byte-identical.
pub fn splice(original: &str, block: &str) -> Result<String> {
    let begin = original
        .find(BEGIN)
        .with_context(|| format!("marker not found: {BEGIN}"))?;
    let begin_line_end = original[begin..]
        .find('\n')
        .map(|offset| begin + offset + 1)
        .unwrap_or(original.len());

    let end = original[begin_line_end..]
        .find(END)
        .map(|offset| begin_line_end + offset)
        .with_context(|| format!("marker not found: {END}"))?;

    let mut out = String::with_capacity(original.len() + block.len());
    out.push_str(&original[..begin_line_end]);
    out.push_str(block);
    out.push_str(&original[end..]);
    Ok(out)
}

/// Rewrites `path` and returns the number of emitted constants.
pub fn update_file(path: &Path, entries: &[Entry], source: &str) -> Result<usize> {
    let original =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let block = render(entries, source);
    let updated = splice(&original, &block)?;

    if updated == original {
        return Ok(block.matches("ObservedCommand {").count());
    }

    std::fs::write(path, updated).with_context(|| format!("writing {}", path.display()))?;
    Ok(block.matches("ObservedCommand {").count())
}

/// Finds `crates/mystique-protocol/src/commands.rs` from either the workspace root or
/// the `rust/` directory.
pub fn default_path() -> Option<PathBuf> {
    const RELATIVE: &str = "crates/mystique-protocol/src/commands.rs";
    const FROM_RUST: &str = "rust/crates/mystique-protocol/src/commands.rs";

    for candidate in [RELATIVE, FROM_RUST] {
        let path = PathBuf::from(candidate);
        if path.is_file() {
            return Some(path);
        }
    }
    None
}

/// Refuses to write into a file that has no generated block.
pub fn check_target(path: &Path) -> Result<()> {
    let text =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    if !text.contains(BEGIN) || !text.contains(END) {
        bail!(
            "{} has no generated block; refusing to rewrite it",
            path.display()
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(cmd: u8, result: u8, echoed: bool) -> Entry {
        let mut entry = Entry::new(0, cmd, "init", &[]);
        entry.replied = true;
        entry.echo = Some(if echoed { cmd } else { 0x00 });
        entry.result_code = Some(result);
        entry.reply_len = Some(48);
        entry.elapsed_ms = 3;
        entry.outcome = "reply".into();
        entry
    }

    #[test]
    fn emits_only_commands_that_replied() {
        let mut silent = Entry::new(1, 0x42, "data", &[]);
        silent.outcome = "timeout".into();
        let mut neutral = Entry::new(2, 0x43, "data", &[]);
        neutral.replied = true;
        neutral.echo = Some(0x00);
        neutral.outcome = "reply".into();

        let block = render(
            &[entry(0x10, 0x00, true), silent, neutral],
            "re/reports/x.json",
        );
        assert!(block.contains("code: 0x10"));
        assert!(!block.contains("code: 0x42"));
        assert!(!block.contains("code: 0x43"));
    }

    #[test]
    fn dedupes_and_prefers_a_successful_reply() {
        let rejected = entry(0x0A, 0x02, true);
        let accepted = entry(0x0A, 0x00, true);
        let block = render(&[rejected, accepted], "re/reports/x.json");
        assert_eq!(block.matches("ObservedCommand {").count(), 1);
        assert!(block.contains("grade: Evidence::Inferred"));
    }

    #[test]
    fn sorts_by_command_byte() {
        let block = render(
            &[
                entry(0x12, 0, true),
                entry(0x02, 0, true),
                entry(0x10, 0, true),
            ],
            "re/reports/x.json",
        );
        let first = block.find("code: 0x02").unwrap();
        let second = block.find("code: 0x10").unwrap();
        let third = block.find("code: 0x12").unwrap();
        assert!(first < second && second < third);
    }

    #[test]
    fn records_the_source_pipe_and_grade() {
        let mut status = Entry::new(0, 0x10, "data", &[]);
        status.replied = true;
        status.echo = Some(0x10);
        status.result_code = Some(0x00);
        status.reply_len = Some(48);
        status.outcome = "reply".into();

        let block = render(&[status], "re/reports/explore-1.json");
        assert!(block.contains("pipes: &[Pipe::Data]"));
        assert!(block.contains("grade: Evidence::Inferred"));
        assert!(block.contains("re/reports/explore-1.json"));
    }

    #[test]
    fn an_unmapped_command_stays_unknown() {
        let block = render(&[entry(0xA1, 0, true)], "re/reports/explore-1.json");
        assert!(block.contains("code: 0xA1"));
        assert!(block.contains("pipes: &[Pipe::Init]"));
        assert!(block.contains("grade: Evidence::Unknown"));
    }

    #[test]
    fn a_payloaded_echo_is_marked_payload_gated() {
        let mut payloaded = Entry::new(0, 0x0A, "data", &[0xEA, 0x07, 0x08, 0x09]);
        payloaded.replied = true;
        payloaded.echo = Some(0x0A);
        payloaded.result_code = Some(0x00);
        payloaded.reply_len = Some(48);
        payloaded.outcome = "reply".into();

        let block = render(&[payloaded], "re/reports/probe-1.json");
        assert!(block.contains("payload_gated: true"));
        assert!(block.contains("pipes: &[Pipe::Data]"));
        assert!(block.contains("grade: Evidence::Inferred"));
    }

    #[test]
    fn splices_without_touching_the_rest_of_the_file() {
        let original = format!(
            "// hand-written\npub const X: u8 = 1;\n{BEGIN}\nold\n{END}\npub const Y: u8 = 2;\n"
        );
        let updated = splice(&original, "// new\n").unwrap();
        assert!(updated.starts_with("// hand-written\npub const X: u8 = 1;\n"));
        assert!(updated.contains("// new\n"));
        assert!(!updated.contains("old"));
        assert!(updated.ends_with("pub const Y: u8 = 2;\n"));
    }

    #[test]
    fn refuses_a_file_without_markers() {
        let error = splice("no markers here\n", "").unwrap_err();
        assert!(error.to_string().contains("marker not found"));
    }

    #[test]
    fn an_empty_report_emits_an_empty_table() {
        let block = render(&[], "re/reports/empty.json");
        assert!(block.contains("pub const OBSERVED_COMMANDS: &[ObservedCommand] = &["));
        assert!(block.contains("];"));
        assert_eq!(block.matches("ObservedCommand {").count(), 0);
    }

    #[test]
    fn updates_a_real_file_in_place() {
        let dir = std::env::temp_dir().join("mystique-emit-test");
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("commands.rs");
        let original = format!("// hand-written\n{BEGIN}\nold\n{END}\n");
        std::fs::write(&path, &original).unwrap();

        let count = update_file(&path, &[entry(0x10, 0, true)], "re/reports/x.json").unwrap();
        assert_eq!(count, 1);

        let updated = std::fs::read_to_string(&path).unwrap();
        assert!(updated.starts_with("// hand-written\n"));
        assert!(updated.contains("code: 0x10"));
        assert!(updated.contains(BEGIN));
        assert!(updated.contains(END));
        assert!(!updated.contains("old"));
    }

    #[test]
    fn refuses_to_rewrite_a_file_without_markers() {
        let dir = std::env::temp_dir().join("mystique-emit-refuse");
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("bare.rs");
        std::fs::write(&path, "pub const X: u8 = 1;\n").unwrap();
        assert!(check_target(&path).is_err());
    }
}
